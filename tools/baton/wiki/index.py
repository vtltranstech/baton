"""docs/context/codebase-map.md: a table row per page, spliced between markers; hand-written lines survive.

ASCII only, one fact per cell: humans scan it, agents parse it.
"""

from __future__ import annotations

from pathlib import Path

from baton import miniyaml
from baton.doclint import to_ascii
from baton.extract.repos import UNKNOWN
from baton.wiki.facts import CATEGORIES, DEPENDENCIES_FILE
from baton.wiki.page import PageError, parse, write_atomic

MAP_FILE = "docs/context/codebase-map.md"
WIKI_DIR = "docs/wiki"
_BEGIN = "<!-- wiki-index: generated by baton wiki and baton verify; do not edit -->"
_END = "<!-- /wiki-index -->"
_UNVERIFIED = "UNVERIFIED, do not cite"
_HEADER = "| Page | Status | Data (collections, topics, files) | APIs (exposed, called) |"


def _commits(central: Path) -> dict[str, str]:
    try:
        document = miniyaml.loads((central / DEPENDENCIES_FILE).read_text(encoding="utf-8"))
    except (OSError, ValueError, UnicodeDecodeError):
        return {}
    return {str(e.get("repo")): str(e.get("commit", UNKNOWN)) for e in document.get("repos") or []}


def _cell(values) -> str:
    return ", ".join(f"`{v}`" for v in values) if values else "-"


def _line(path: Path, central: Path, commit: str | None) -> str:
    rel = path.relative_to(central).as_posix()
    try:
        front = parse(path.read_text(encoding="utf-8")).front
    except (PageError, OSError, UnicodeDecodeError) as exc:
        return f"| `{rel}` | {_UNVERIFIED} ({exc}) | - | - |"
    generated = front.get("generatedFrom")
    citable = front.get("verified") is True and generated == commit and commit not in (None, UNKNOWN)
    status = f"verified @{generated}" if citable else f"{_UNVERIFIED} (@{generated})"
    claims = front.get("claims") if isinstance(front.get("claims"), dict) else {}

    def values(*categories: str) -> list[str]:
        out: list[str] = []
        for category in categories:
            if category in CATEGORIES and isinstance(claims.get(category), list):
                out += [str(v) for v in claims[category]]
        return out

    data = _cell(values("collections", "topics", "files"))
    apis = _cell(values("endpoints", "calls"))
    return f"| `{rel}` | {status} | {data} | {apis} |"


def regenerate(central: Path) -> Path:
    """Rewrites the index for every repo under docs/wiki. Page state comes from the files."""
    commits = _commits(central)
    lines = [_BEGIN, "# Codebase map", ""]
    wiki = central / WIKI_DIR
    for repo_dir in sorted(p for p in wiki.iterdir() if p.is_dir()) if wiki.is_dir() else []:
        lines += [f"## {repo_dir.name}", "", _HEADER, "| --- | --- | --- | --- |"]
        lines += [_line(p, central, commits.get(repo_dir.name)) for p in sorted(repo_dir.glob("*.md"))]
        lines.append("")
    lines.append(_END)
    block = "\n".join(lines) + "\n"
    target = central / MAP_FILE
    existing = target.read_text(encoding="utf-8") if target.is_file() else ""
    if _BEGIN in existing and _END in existing:
        head, rest = existing.split(_BEGIN, 1)
        tail = rest.split(_END, 1)[1].lstrip("\n")
        text = head + block + (f"\n{tail}" if tail else "")
    else:
        text = block + (f"\n{existing}" if existing else "")
    if text != existing:
        write_atomic(target, to_ascii(text))
    return target
