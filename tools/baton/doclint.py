import json
import re
import sys
import unicodedata
from dataclasses import dataclass
from pathlib import Path

MAX_BULLET_WORDS = 20
MAX_PARAGRAPH_WORDS = 40
MAX_PARAGRAPH_SENTENCES = 2
MAX_HEADING = 60
OWNED = (
    "docs/changes/",
    "docs/decisions/",
    "docs/context/",
    "docs/releases/",
    "docs/status.md",
    "docs/metrics.md",
)
