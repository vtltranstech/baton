def _named(ch: str) -> str:
    """A letter from another script by its name (GREEK CAPITAL LETTER SIGMA -> Sigma); anything else -> ?."""
    name = unicodedata.name(ch, "")
    if " LETTER " in f" {name} ":
        word = name.split()[-1]
        return word.capitalize() if "CAPITAL" in name else word.lower()
    return "?"


def to_ascii(text: str, xml: bool = False) -> str:
    """Always ASCII: known characters by the table, accented letters lose the accent, letters of other
    scripts by name, anything else becomes `?`."""
    if text.isascii():
        return text
    out = []
    for ch in text:
        if ord(ch) < 128:
            out.append(ch)
        elif xml and ch in _XML_UNSAFE:
            out.append(_XML_UNSAFE[ch])
        elif ch in _ASCII:
            out.append(_ASCII[ch])
        else:
            folded = "".join(c for c in unicodedata.normalize("NFKD", ch) if ord(c) < 128)
            out.append(folded or _named(ch))
    return "".join(out)


@dataclass
class Problem:
    path: str
    line: int
    rule: str
    message: str

    def __str__(self) -> str:
        return f"{self.path}:{self.line}: {self.rule}: {self.message}"


def _words(text: str) -> int:
    text = re.sub(r"`[^`]*`", "CODE", text)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", "LINK", text)
    text = re.sub(r"\*\*|__", "", text)
    return len([w for w in re.split(r"\s+", text.strip()) if re.search(r"\w", w)])


def _sentences(text: str) -> int:
    text = re.sub(r"`[^`]*`", "CODE", text)
    text = re.sub(r"\b(e\.g|i\.e|etc|vs|approx|no)\.", "X", text, flags=re.I)
    return len([s for s in re.split(r"(?<=[.!?])\s+(?=[A-Z0-9`*])", text.strip()) if s])


def is_generated(text: str) -> bool:
    head = text[:600]
    marker = "generated by" in head.lower() and "<!--" in head
    return marker or head.startswith("---\n") and "bodySha256" in text[:3000]


def owned(rel: str) -> bool:
    return any(rel == p or rel.startswith(p) for p in OWNED)


def check(text: str, rel: str, style: bool | None = None) -> list[Problem]:
    """Problems in one document. `style` None: decided by the path and the generated marker."""
    problems: list[Problem] = []
    if style is None:
        style = owned(rel) and not is_generated(text)
    lines = text.splitlines()
    in_code = in_front = in_comment = False
    paragraph: list[tuple[int, str]] = []
    quote: list[int] = []

    def flush() -> None:
        if paragraph and style:
            body = " ".join(t for _, t in paragraph)
            words, sentences = _words(body), _sentences(body)
            if words > MAX_PARAGRAPH_WORDS or sentences > MAX_PARAGRAPH_SENTENCES:
                problems.append(
                    Problem(
                        rel,
                        paragraph[0][0],
                        "paragraph",
                        f"{sentences} sentences, {words} words: use a table or bullets "
                        f"(max {MAX_PARAGRAPH_SENTENCES} sentences, {MAX_PARAGRAPH_WORDS} words)",
                    )
                )
        paragraph.clear()

    def flush_quote() -> None:
        if quote and style:
            first = lines[quote[0] - 1]
            if len(quote) > 1 or not _CALLOUT.match(first):
                problems.append(
                    Problem(
                        rel,
                        quote[0],
                        "note",
                        "a blockquote is one line: > [!NOTE] <text> (or TIP, IMPORTANT, WARNING, CAUTION)",
                    )
                )
        quote.clear()

    for number, raw in enumerate(lines, 1):
        for column, ch in enumerate(raw, 1):
            if ord(ch) > 127:
                problems.append(
                    Problem(
                        rel,
                        number,
                        "ascii",
                        f"non-ASCII U+{ord(ch):04X} {unicodedata.name(ch, '?')} at column "
                        f"{column}; run `baton doclint --fix`",
                    )
                )
                break
        line = raw.rstrip()
        stripped = line.strip()
        if number == 1 and stripped == "---":
            in_front = True
            continue
        if in_front:
            in_front = stripped != "---"
            continue
        if stripped.startswith(("```", "~~~")):
            flush()
            flush_quote()
            in_code = not in_code
            continue
        if in_code:
            continue
        if in_comment or stripped.startswith("<!--"):
            in_comment = "-->" not in stripped
            continue
        if stripped.startswith(">"):
            flush()
            quote.append(number)
            continue
        flush_quote()
        if not stripped:
            flush()
            continue
        if not style:
            continue
        lowered = re.sub(r"`[^`]*`", "", stripped.lower())
        for phrase in FILLER:
            if re.search(rf"(?<![\w-]){re.escape(phrase.strip())}(?![\w-])", lowered):
                problems.append(Problem(rel, number, "filler", f"cut {phrase.strip()!r}: say the fact"))
                break
        if stripped.startswith("#"):
            flush()
            heading = stripped.lstrip("#").strip()
            if len(heading) > MAX_HEADING:
                problems.append(
                    Problem(rel, number, "heading", f"{len(heading)} characters (max {MAX_HEADING})")
                )
            continue
        if stripped.startswith("|") or stripped.startswith("<"):
            flush()
            continue
        item = re.match(r"^(?:[-*+]|\d+[.)])\s+(?:\[[ xX]\]\s+)?(.*)$", stripped)
        if item:
            flush()
            words = _words(item.group(1))
            if words > MAX_BULLET_WORDS:
                problems.append(
                    Problem(
                        rel,
                        number,
                        "bullet",
                        f"{words} words (max {MAX_BULLET_WORDS}): split it or use a table",
                    )
                )
            continue
        if raw.startswith(("  ", "\t")) and not paragraph:
            continue  # continuation of a list item
        paragraph.append((number, stripped))
    flush()
    flush_quote()
    return problems


def _files(central: Path, paths: list[str]) -> list[Path]:
    targets = [central / p if not Path(p).is_absolute() else Path(p) for p in paths] or [central / "docs"]
    out: list[Path] = []
    for target in targets:
        if target.is_dir():
            out += sorted(
                p for p in target.rglob("*.md") if not any(part.startswith(".") for part in p.parts)
            )
        elif target.is_file():
            out.append(target)
    return out


def add_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("paths", nargs="*", help="files or folders (default docs/)")
    parser.add_argument("--fix", action="store_true", help="replace non-ASCII characters with ASCII in place")
    parser.add_argument(
        "--all-rules", action="store_true", help="apply the style rules to every file, not only owned docs"
    )


def run(args: argparse.Namespace) -> int:
    central = Path(args.central).resolve()
    problems: list[Problem] = []
    fixed: list[str] = []
    for path in _files(central, args.paths):
        try:
            rel = path.resolve().relative_to(central).as_posix()
        except ValueError:
            rel = str(path)
        text = path.read_text(encoding="utf-8", errors="replace")
        if args.fix:
            new = to_ascii(text)
            if new != text:
                path.write_text(new, encoding="utf-8")
                fixed.append(rel)
                text = new
        problems += check(text, rel, True if args.all_rules else None)
    if args.json:
        print(json.dumps({"fixed": fixed, "problems": [p.__dict__ for p in problems]}, indent=2))
    else:
        for rel in fixed:
            print(f"fixed characters: {rel}")
        for problem in problems:
            print(problem, file=sys.stderr)
        if not problems:
            print("doclint: clean")
    return 1 if problems else 0
