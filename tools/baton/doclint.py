"""Checks Markdown docs against the doc-style skill; `--fix` replaces non-ASCII characters with ASCII.

Rules (code fences, front matter and HTML comments are skipped):
  ascii      every character is ASCII                                        all docs
  bullet     a list item has at most 20 words (inline code and links count 1)  owned docs
  paragraph  a prose paragraph has at most 2 sentences and 40 words            owned docs
  filler     no filler phrases ("it is important to note", "in order to", ...) owned docs
  note       a blockquote is one line and starts with > [!NOTE|TIP|IMPORTANT|WARNING|CAUTION]  owned docs
  heading    a heading has at most 60 characters                               owned docs
Owned docs are the documentation agent's: change notes, decisions, context (codebase map, pitfalls),
status, metrics, release notes. Generated files (a `generated by` marker or wiki front matter) get the
ascii rule only.
"""

from __future__ import annotations

