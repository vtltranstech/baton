"""The project's architecture as pictures: system context, containers with their data, components per repo.

Same sources as `baton c4` (the graph and profile/) plus the code map for the calls between components, so
these views and docs/architecture/workspace.dsl describe the same system. Written to
docs/architecture/diagrams/.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

from baton.diagram import draw_flow, mermaid, output
from baton.diagram.codemap import ClassInfo
from baton.diagram.shapes import CONTEXT, Flow, Lane, Link, Node
from baton.diagram.shapes import merge_label as _merge
from baton.diagram.world import World, load_world
from baton.graph.model import node_name, node_prefix

OUT = "docs/architecture/diagrams"
MAX_COMPONENTS = 60
_ENTRY = {"controller", "listener", "screen", "config", "application"}
_ADAPTER = {"repository", "adapter", "client", "publisher", "hook"}
_SKIP = {"dto", "document", "value", "enum", "interface", "application"}
_LABEL = {
    "READS_COLLECTION": "read",
    "WRITES_COLLECTION": "write",
    "PUBLISHES": "publish",
    "CONSUMES": "consume",
    "READS_FILE": "read",
    "WRITES_FILE": "write",
}


def _resource_node(resource: str, world: World) -> Node:
    prefix = node_prefix(resource)
    kind = {"collection": "store", "topic": "queue", "queue": "queue", "file": "file", "job": "job"}.get(
        prefix, "external"
    )
    lane = {"collection": "data", "topic": "messaging", "queue": "messaging", "file": "files"}.get(
        prefix, "external"
    )
    sub = {
        "collection": f"collection - {world.datastore()}",
        "topic": f"topic - {world.broker(resource)}",
        "queue": f"queue - {world.broker(resource)}",
        "file": "file",
        "endpoint": "REST, provider outside the graph",
    }.get(prefix, prefix)
    return Node(resource, node_name(resource), kind, CONTEXT, sub, lane)


def _inbound(nodes: dict, links) -> None:
    """A queue, topic or file that only feeds the product sits in a lane above the entry points."""
    sources = {lk.src for lk in links}
    targets = {lk.dst for lk in links}
    for node in nodes.values():
        if node.lane in ("messaging", "files") and node.id in sources and node.id not in targets:
            node.lane = "inbound"


def context_view(world: World) -> Flow:
    profile = world.profile
    nodes = [
        Node(
            "product", profile.name, "component", CONTEXT, profile.one_liner[:60] or "the product", "product"
        )
    ]
    links = []
    for persona in profile.personas:
        nodes.append(Node(f"actor:{persona}", persona, "person", CONTEXT, "person", "people"))
        links.append(Link(f"actor:{persona}", "product", "uses", CONTEXT))
    for name, description in profile.externals:
        nodes.append(Node(f"ext:{name}", name, "external", CONTEXT, description[:48], "external"))
        links.append(Link("product", f"ext:{name}", "integrates", CONTEXT))
    unknown = sorted(
        {e.dst for e in world.edges if e.kind == "CALLS_ENDPOINT" and not world.edges_to(e.dst, "EXPOSES")}
    )
    for resource in unknown:
        nodes.append(
            Node(
                resource,
                node_name(resource),
                "external",
                CONTEXT,
                "called; provider not in the graph",
                "external",
            )
        )
        links.append(Link("product", resource, "calls", CONTEXT))
    lanes = [
        Lane("people", "People"),
        Lane("product", "Product", f"{len(world.maps)} repos"),
        Lane("external", "External systems"),
    ]
    return Flow(
        f"{profile.name} - system context",
        f"generated by `baton diagram architecture` - {world.commits()}",
        lanes,
        nodes,
        links,
        "Who uses the product and which systems outside it the code talks to.",
    )


def container_view(world: World) -> Flow:
    """One box per deployable unit (a monorepo's modules are separate units). A collection used by one unit
    folds into that unit's store box; a collection two units share stays visible: it is a seam."""
    nodes: dict[str, Node] = {}
    links: dict[tuple[str, str, str], Link] = {}

    def add(node: Node) -> None:
        nodes.setdefault(node.id, node)

    def link(src: str, dst: str, label: str, style: str) -> None:
        if src == dst:
            return
        key = (src, dst, style)
        if key in links:
            _merge(links[key], label)
        else:
            links[key] = Link(src, dst, label, CONTEXT, style)

    def unit_of(edge) -> str:
        return world.unit_of(edge.repo, edge.file)

    document_classes = {f"class:{c.fqcn}" for c in world.classes() if c.stereotype == "document"}
    for persona in world.profile.personas[:1]:
        add(Node(f"actor:{persona}", persona, "person", CONTEXT, "person", "people"))
    for unit in world.units():
        repo = world.repo_of_unit(unit)
        add(Node(f"unit:{unit}", unit, "component", CONTEXT, world.repo_tech(repo), "product"))
        if "React" in world.repo_tech(repo) and world.profile.personas and repo == unit:
            link(f"actor:{world.profile.personas[0]}", f"unit:{unit}", "uses", "sync")
    users: dict[str, set[str]] = {}
    for edge in world.edges:
        if node_prefix(edge.dst) == "collection" and edge.src not in document_classes:
            users.setdefault(edge.dst, set()).add(unit_of(edge))
    private: dict[str, list[str]] = {}
    for collection, owners in users.items():
        if len(owners) == 1:
            private.setdefault(next(iter(owners)), []).append(node_name(collection))
    for edge in world.edges:
        if edge.kind in ("OWNED_BY", "EXPOSES", "RUNS_JOB") or edge.src in document_classes:
            continue
        src = f"unit:{unit_of(edge)}"
        if src not in nodes:
            continue
        if edge.kind == "CALLS_ENDPOINT":
            providers = world.edges_to(edge.dst, "EXPOSES")
            if providers:
                link(src, f"unit:{unit_of(providers[0])}", node_name(edge.dst), "sync")
            else:
                add(_resource_node(edge.dst, world))
                link(src, edge.dst, "call", "sync")
            continue
        if edge.kind not in _LABEL:
            continue
        target = edge.dst
        if node_prefix(edge.dst) == "collection" and len(users.get(edge.dst, ())) == 1:
            unit = unit_of(edge)
            target = f"store:{unit}"
            count = len(private[unit])
            add(
                Node(
                    target,
                    f"{unit} data",
                    "store",
                    CONTEXT,
                    f"{count} collections - {world.datastore()}",
                    "data",
                )
            )
        else:
            add(_resource_node(edge.dst, world))
            if node_prefix(edge.dst) == "collection":
                nodes[edge.dst].sub = f"shared by {len(users[edge.dst])} services"
        verb = _LABEL[edge.kind]
        if edge.kind in ("CONSUMES", "READS_FILE"):
            link(target, src, verb, "async" if edge.kind == "CONSUMES" else "data")
        else:
            link(src, target, verb, "async" if edge.kind == "PUBLISHES" else "data")
    _inbound(nodes, links.values())
    lanes = [
        Lane("people", "People"),
        Lane("inbound", "Inbound", "queues, topics, files the product only reads"),
        Lane("product", world.profile.name, f"{len(world.units())} deployable units"),
        Lane("data", "Data", world.datastore()),
        Lane("messaging", "Messaging"),
        Lane("files", "Files"),
        Lane("external", "External"),
    ]
    shared = sum(1 for owners in users.values() if len(owners) > 1)
    return Flow(
        f"{world.profile.name} - containers and data",
        f"generated by `baton diagram architecture` - {world.commits()}",
        lanes,
        list(nodes.values()),
        list(links.values()),
        f"{len(users)} collections: {shared} shared between services (drawn), the rest folded into each "
        "service's data box. Every topic, queue, file and REST call between services is drawn.",
    )


def _role(info: ClassInfo) -> str:
    if info.stereotype in _ENTRY:
        return "entry"
    if info.stereotype in _ADAPTER:
        return "adapters"
    return "application"


def component_view(world: World, unit: str) -> Flow | None:
    repo = world.repo_of_unit(unit)
    cmap = world.maps[repo]
    keep = {f: c for f, c in cmap.classes.items() if c.stereotype not in _SKIP and world.unit(c) == unit}
    if not keep:
        return None
    grouped = len(keep) > MAX_COMPONENTS

    packages = [c.fqcn.rsplit(".", 1)[0].split(".") for c in keep.values()]
    root = os.path.commonprefix(packages) if packages else []

    def key(info: ClassInfo) -> str:
        if not grouped:
            return f"class:{info.fqcn}"
        package = info.fqcn.rsplit(".", 1)[0].split(".")
        return "pkg:" + ".".join(package[len(root) :] or package[-1:])

    nodes: dict[str, Node] = {}
    links: dict[tuple[str, str, str], Link] = {}
    roles: dict[str, list[str]] = {}
    for info in keep.values():
        k = key(info)
        roles.setdefault(k, []).append(_role(info))
        if k not in nodes:
            label = info.name if not grouped else k[4:]
            kind = "screen" if info.stereotype == "screen" else "component"
            nodes[k] = Node(k, label, kind, CONTEXT, info.stereotype, _role(info))
    if grouped:  # a package sits with its entry points if it has one, else where most of its classes are
        for k, node in nodes.items():
            found = roles[k]
            node.lane = "entry" if "entry" in found else max(sorted(set(found)), key=found.count)
            node.sub = f"package - {len(found)} components"

    def link(src: str, dst: str, label: str, style: str) -> None:
        if src == dst:
            return
        k = (src, dst, style)
        if k in links:
            _merge(links[k], label)
        else:
            links[k] = Link(src, dst, label, CONTEXT, style)

    for info in keep.values():
        class_level = [(None, use) for use in info.uses]
        for m in [None, *info.methods]:
            for call in m.calls if m else []:
                if call.via == "new":
                    continue
                target = cmap.classes.get(cmap.implementation(call.target))
                if target is None or target.fqcn not in keep:
                    continue
                link(key(info), key(target), f"{call.method}()", "sync")
            for use in m.uses if m else [u for _, u in class_level]:
                if use.kind in _LABEL:
                    node = _resource_node(use.resource, world)
                    nodes.setdefault(node.id, node)
                    if use.kind in ("CONSUMES", "READS_FILE"):
                        link(
                            use.resource,
                            key(info),
                            _LABEL[use.kind],
                            "async" if use.kind == "CONSUMES" else "data",
                        )
                    else:
                        link(
                            key(info),
                            use.resource,
                            _LABEL[use.kind],
                            "async" if use.kind == "PUBLISHES" else "data",
                        )
                elif use.kind in ("EXPOSES", "CALLS_ENDPOINT"):
                    resource = use.resource
                    if use.kind == "CALLS_ENDPOINT" and not world.edges_to(resource, "EXPOSES"):
                        node = _resource_node(resource, world)
                        nodes.setdefault(node.id, node)
                        link(key(info), resource, "call", "sync")
                elif use.kind == "RUNS_JOB":
                    jid = use.resource
                    nodes.setdefault(jid, Node(jid, node_name(jid), "job", CONTEXT, "batch job", "entry"))
                    link(key(info), jid, "runs", "sync")
    _inbound(nodes, links.values())
    lanes = [
        Lane("inbound", "Inbound", "queues, topics, files only read here"),
        Lane("entry", "Entry points", "controllers, listeners, jobs, screens"),
        Lane("application", "Application", "services and domain logic"),
        Lane("adapters", "Adapters", "repositories, clients, publishers"),
        Lane("data", "Data", world.datastore()),
        Lane("messaging", "Messaging"),
        Lane("files", "Files"),
        Lane("external", "External"),
    ]
    caption = (
        f"{len(keep)} components grouped by package (more than {MAX_COMPONENTS})."
        if grouped
        else "Components and the calls between them, read from the code; interfaces are drawn as their "
        "implementation."
    )
    return Flow(
        f"{unit} - components",
        f"generated by `baton diagram architecture` - {repo} @ {cmap.commit}",
        lanes,
        list(nodes.values()),
        list(links.values()),
        caption,
    )


def run(args, central: Path) -> int:
    world = load_world(central)
    sections = [
        output.Section(
            "1. System context", "context.svg", "", lead="Who uses the product and what is outside it."
        ),
        output.Section(
            "2. Containers and data",
            "containers.svg",
            "",
            lead="Services, their data, and the calls and messages between them.",
        ),
    ]
    views = [context_view(world), container_view(world)]
    for unit in world.units():
        if args.repo and args.repo not in (unit, world.repo_of_unit(unit)):
            continue
        view = component_view(world, unit)
        if view is not None:
            sections.append(
                output.Section(f"3. Components: {unit}", f"components-{unit}.svg", "", lead=view.caption)
            )
            views.append(view)
    for section, view in zip(sections, views, strict=True):
        section.svg = draw_flow.draw(view)
        section.mermaid = mermaid.flow(view)
    rows = [
        "| Service | Repo | Stack | Components | Endpoints | Collections | Topics and queues | Commit |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for unit in world.units():
        repo = world.repo_of_unit(unit)
        cmap = world.maps[repo]
        mine = [c for c in cmap.classes.values() if world.unit(c) == unit]
        uses = {(u.kind, u.resource) for c in mine for m in c.methods for u in m.uses + c.uses}
        count = {
            "comps": sum(1 for c in mine if c.stereotype not in _SKIP),
            "eps": len({r for k, r in uses if k == "EXPOSES"}),
            "cols": len({r for k, r in uses if node_prefix(r) == "collection"}),
            "msgs": len({r for k, r in uses if node_prefix(r) in ("topic", "queue")}),
        }
        rows.append(
            f"| {unit} | {repo} | {world.repo_tech(repo)} | {count['comps']} | {count['eps']} | "
            f"{count['cols']} | {count['msgs']} | {cmap.commit} |"
        )
    notes = [f"not checked out, not drawn: {', '.join(world.missing)}"] if world.missing else []
    diagram_set = output.DiagramSet(
        f"{world.profile.name} - architecture",
        "> [!NOTE] Generated from the code by `baton diagram architecture`. Re-run after a merge.",
        sections,
        [("Services", "\n".join(rows))],
        notes,
        {"repos": list(world.maps), "missing": world.missing},
    )
    out = Path(args.out) if args.out else central / OUT
    if not out.is_absolute():
        out = central / out
    files = output.write(out, diagram_set)
    rel = out.relative_to(central).as_posix() if out.is_relative_to(central) else str(out)
    if args.json:
        print(json.dumps({"out": rel, "files": files, "missing": world.missing}, indent=2))
    else:
        print(f"wrote {rel}/ ({len(files)} files): open diagrams.md in the VS Code preview or index.html")
        for note in notes:
            print(f"  note: {note}", file=sys.stderr)
    return 0
