"""W4 fixtures. Helpers are in w4_helpers.py, so they cannot collide with another worktree's conftest."""

import json
import stat
import sys
from pathlib import Path

import jsonschema
import pytest

sys.path.insert(0, str(Path(__file__).parent))

from w4_helpers import REPO, ROOT, STUB, frontmatter, make_git_repo, run_cli, write_central  # noqa: E402


@pytest.fixture
def stub(tmp_path, monkeypatch):
    """A `claude` that logs each call and answers per STUB_MODE. Returns the list of calls so far."""
    script = tmp_path / "stub-claude"
    script.write_text(STUB.format(python=sys.executable))
    script.chmod(script.stat().st_mode | stat.S_IEXEC)
    log = tmp_path / "stub-log.jsonl"
    log.write_text("")
    monkeypatch.setenv("BATON_CLAUDE_BIN", str(script))
    monkeypatch.setenv("STUB_LOG", str(log))
    monkeypatch.delenv("STUB_MODE", raising=False)

    def calls() -> list[dict]:
        return [json.loads(line) for line in log.read_text().splitlines()]

    return calls


@pytest.fixture
def repo(tmp_path) -> Path:
    return make_git_repo(tmp_path / "repos" / REPO)


@pytest.fixture
def central(tmp_path, repo) -> Path:
    """A central repo over the git copy, extracted, no wiki yet."""
    path = write_central(tmp_path / "central", repo)
    assert run_cli("extract", "--central", str(path)) == 0
    return path


@pytest.fixture
def generated(central, stub) -> Path:
    """The same, with every page generated by the stub. Not verified."""
    assert run_cli("wiki", REPO, "--central", str(central)) == 0
    return central


@pytest.fixture
def validate_page():
    schema = json.loads((ROOT / "schemas" / "wiki-page.json").read_text())

    def check(path: Path) -> dict:
        data = frontmatter(path)
        jsonschema.validate(data, schema)
        return data

    return check
