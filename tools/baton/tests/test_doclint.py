"""baton doclint and the doc-lint hook: the doc-style rules, ASCII fixing, generated output stays clean."""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

from baton.cli import main
from baton.doclint import check, to_ascii

ROOT = Path(__file__).resolve().parents[3]
GOOD = """# S-010 Waive dormant fees

| Field | Value |
| --- | --- |
| Date | 2026-11-03 |

## What changed
- **FeeService#accrue:** skips the fee when the account is dormant.

> [!WARNING] Create the index before deploy.

```text
a long code line with many many many many many many many many many many many many words and no rule
```
"""


def rules(text: str, rel: str = "docs/changes/F-1/S-1-change-note.md") -> list[str]:
    return [p.rule for p in check(text, rel)]


def test_a_dense_change_note_is_clean():
    assert rules(GOOD) == []


def test_each_rule_fires():
    assert rules("# T\n\nUse it \u2014 now.\n") == ["ascii"]
    assert rules("# T\n\n- " + "word " * 21 + "\n") == ["bullet"]
    assert rules("# T\n\n- **Term:** `a very long code span counts as one word` and link [x](y)\n") == []
    assert rules("# T\n\nOne. Two. Three.\n") == ["paragraph"]
    assert rules("# T\n\n" + "word " * 41 + "\n") == ["paragraph"]
    assert rules("# T\n\n- It is important to note the cap.\n") == ["filler"]
    assert rules("# T\n\n> plain quote\n") == ["note"]
    assert rules("# T\n\n> [!NOTE] one\n> two\n") == ["note"]
    assert rules("# " + "x" * 61 + "\n") == ["heading"]


def test_style_rules_only_on_owned_docs_ascii_everywhere():
    long = "# T\n\nOne. Two. Three.\n\nArrow \u2192 here.\n"
    assert rules(long, "docs/stories/F-1/S-1.md") == ["ascii"]
    assert rules(long, "docs/status.md") == ["paragraph", "ascii"]
    generated = "<!-- generated by `baton diagram` -->\n# T\n\nOne. Two. Three.\n"
    assert rules(generated, "docs/context/x.md") == []


def test_to_ascii_maps_the_usual_characters():
    text = (
        "a \u2014 b \u2192 c \u00b7 d \u2026 \u201cq\u201d \u00abs\u00bb \u2265 1 \u00a7 2 caf\u00e9 \u00f7"
    )
    assert to_ascii(text) == 'a - b -> c - d ... "q" <<s>> >= 1 section  2 cafe /'
    assert to_ascii("\u00abservice\u00bb", xml=True) == "&lt;&lt;service&gt;&gt;"
    assert to_ascii("\u03a3 amounts \u03b1 \U0001f600") == "Sigma amounts alpha ?"


def test_cli_fix_rewrites_characters_and_reports_the_rest(tmp_path, capsys):
    note = tmp_path / "docs" / "changes" / "F-1" / "S-1-change-note.md"
    note.parent.mkdir(parents=True)
    note.write_text("# T\n\n- **A:** x \u2192 y.\n- " + "w " * 25 + "\n")
    code = main(["doclint", "--central", str(tmp_path), "--fix"])
    out = capsys.readouterr()
    assert code == 1
    assert note.read_text().startswith("# T\n\n- **A:** x -> y.")
    assert "S-1-change-note.md:4: bullet" in out.err and "ascii" not in out.err


def run_hook(tmp_path: Path, file_path: str) -> subprocess.CompletedProcess:
    payload = {"tool_name": "Write", "tool_input": {"file_path": file_path}, "cwd": str(tmp_path)}
    env = {**os.environ, "CLAUDE_PROJECT_DIR": str(tmp_path)}
    return subprocess.run(
        [sys.executable, str(ROOT / "hooks" / "doc_lint.py")],
        input=json.dumps(payload),
        capture_output=True,
        text=True,
        env=env,
    )


def test_hook_hands_problems_back_and_ignores_other_files(tmp_path):
    (tmp_path / "profile").mkdir()
    (tmp_path / "profile" / "project.md").write_text("# p\n")
    status = tmp_path / "docs" / "status.md"
    status.parent.mkdir()
    status.write_text("# Status\n\nThe story moved on. It is now in review. Next is QA.\n")
    done = run_hook(tmp_path, str(status))
    assert done.returncode == 2 and "docs/status.md:3: paragraph" in done.stderr
    status.write_text("# Status\n\n| Story | State |\n| --- | --- |\n| S-1 | In Review |\n")
    assert run_hook(tmp_path, str(status)).returncode == 0
    other = tmp_path / "README.md"
    other.write_text("Arrow \u2192 and long prose. Two. Three.\n")
    assert run_hook(tmp_path, str(other)).returncode == 0


def test_instruction_files_are_ascii():
    """Agents copy the style of their instructions; non-ASCII there comes back in the docs they write."""
    offenders = []
    for folder in ("agents", "skills", "templates", "contracts", "hooks"):
        for path in (ROOT / folder).rglob("*"):
            if path.is_file() and path.suffix in (".md", ".py", ".json", ".dsl", ".csv", ".yaml"):
                if not path.read_text(encoding="utf-8").isascii():
                    offenders.append(str(path.relative_to(ROOT)))
    assert offenders == []


def test_the_doc_style_examples_pass_their_own_lint():
    import re

    text = (ROOT / "skills" / "doc-style" / "SKILL.md").read_text()
    for block in re.findall(r"```markdown\n(.*?)```", text, re.S):
        assert check(block, "docs/changes/F-1/S-1-change-note.md") == []
